 powershell -EncodedCommand          4104        PowerShell/Operational
 Discovery (whoami, net user, ...)   4688 / 1    Security / Sysmon
 Account created                     4720        Security
 Added to Administrators             4732        Security
 Service installed                   7045        System
 Service installed                   4697        Security
