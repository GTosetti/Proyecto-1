<#
    03-generate-known-events.ps1
    ---------------------------------------------------------------------------
    WHAT IT DOES
      Deliberately produces a set of Windows events whose Event ID, timestamp
      and cause you already know, then prints a prediction table.

    WHY IT EXISTS
      This is NOT an attack simulation. It is a known-answer test for the whole
      pipeline. You cannot tell whether a SIEM is working by looking at it -
      an empty dashboard and a broken collector look identical. The only way to
      test detection coverage is to cause an event on purpose and then check
      whether it arrived, which is what this script makes repeatable.

      It is also the honest way to find the gaps. In this lab it is how Event ID
      4697 was found to be generated by Windows, collected by the agent, and
      matched by no rule at all - a hole that is invisible from the dashboard
      because a missing alert produces nothing to look at.

    METHOD - do this in the right order
      1. Run the script.
      2. Copy the printed table into your notes and write down, BEFORE opening
         the SIEM, which events you expect to alert and which you expect to pass
         silently.
      3. Only then open the dashboard and compare.
      A failed prediction is a precisely located knowledge gap. A confirmed
      prediction taught you nothing.

    CLEANUP
      The test account and test service it creates are removed in a finally
      block, so they are cleaned up even if a step fails.

    RUN AS ADMINISTRATOR on the endpoint:
      powershell -ExecutionPolicy Bypass -File .\03-generate-known-events.ps1

    No credential appears in this file. The two passwords this script needs -
    a deliberately wrong one for the failed-logon test, and a throwaway one for
    the temporary account - are generated randomly at run time and never
    printed, stored or reused.
#>

#Requires -Version 5.1
[CmdletBinding()]
param(
    [int]    $FailedLogonCount = 5,
    [string] $NonExistentUser  = 'ghost-user',
    [string] $TestAccountName  = 'svc-labtest',
    [string] $TestServiceName  = 'LabSocTestSvc'
)

$ProgressPreference = 'SilentlyContinue'

function Write-Step($t) { Write-Host "`n=== $t ===" -ForegroundColor Cyan }
function Write-Ok($t)   { Write-Host "  [ok] $t"    -ForegroundColor Green }

function New-ThrowawaySecret {
    <#
      Generates a random secret at run time and hands it back as a SecureString.
      Exists so that no password literal is ever written into this file or
      committed to this repository, and so that nothing generated here can be
      reused anywhere. Includes one character from each class to satisfy Windows
      password complexity.

      PSScriptAnalyzer reports ConvertTo-SecureString -AsPlainText -Force as an
      Error, and in general it is right: the rule exists because the plaintext
      normally comes from a literal in the file, from a prompt, or from
      somewhere it can be read back. Here it comes from the three lines above -
      24 bytes out of a cryptographic RNG, built in memory, converted once, and
      never printed, stored, logged or returned in plain form. Suppressed at the
      single place the conversion happens, with the reason written down, rather
      than by excluding the rule in CI: everywhere else in this repository the
      rule still applies.
    #>
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute(
        'PSAvoidUsingConvertToSecureStringWithPlainText', '',
        Justification = 'The plaintext is a 24-byte CSPRNG value created on the preceding line, converted once and never stored, printed or reused. No password literal exists in this repository.')]
    [OutputType([System.Security.SecureString])]
    param()

    $bytes = New-Object byte[] 24
    $rng   = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($bytes)
    $plain = [Convert]::ToBase64String($bytes) + '!aA1'
    return (ConvertTo-SecureString $plain -AsPlainText -Force)
}

$identity  = [Security.Principal.WindowsIdentity]::GetCurrent()
$principal = New-Object Security.Principal.WindowsPrincipal($identity)
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw 'This script must be run as Administrator.'
}

$start = Get-Date
Write-Host "Start timestamp: $($start.ToString('yyyy-MM-dd HH:mm:ss')) local" -ForegroundColor White
Write-Host "UTC equivalent : $($start.ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ'))" -ForegroundColor White
Write-Host "Record both. The SIEM indexes in UTC and Windows displays local time;" -ForegroundColor White
Write-Host "confusing the two is the single most common reason an event 'is not there'.`n" -ForegroundColor White

# ===========================================================================
# 1 - Failed logons  ->  4625, logon type 2 (interactive)
# ===========================================================================
# Note the logon type. The same "wrong password" fact appears as type 2 from the
# console and as type 3 over SMB from another host, with different
# LogonProcessName and AuthenticationPackage values. Same Event ID, same
# description text, two different stories - see the attacker-side commands at
# the end of this file.
Write-Step "1/5  $FailedLogonCount failed logons against an account that does not exist"

$wrongSecret = New-ThrowawaySecret
for ($i = 1; $i -le $FailedLogonCount; $i++) {
    $cred = New-Object System.Management.Automation.PSCredential($NonExistentUser, $wrongSecret)
    try   { Start-Process -FilePath 'cmd.exe' -Credential $cred -ErrorAction Stop }
    catch { Write-Ok "attempt $i failed (which is the point)" }
    Start-Sleep -Milliseconds 400
}

# ===========================================================================
# 2 - Process tree  ->  4688 + Sysmon 1
# ===========================================================================
# Bread and butter of triage. The field that separates "an administrator
# working" from "something wrong" is the parent, not the process itself.
Write-Step '2/5  Process tree: cmd -> powershell -> whoami'

# Redirection has to be cmd's own, inside the quoted string. An earlier version
# of this line ended `... whoami /all | Out-Null"`, and cmd - not PowerShell -
# parsed that pipe: cmd resolved the right-hand side first, found no command
# called Out-Null, and never started the left-hand side at all. The step printed
# [ok] and produced no tree. Measured: exit code 255, no powershell.exe and no
# whoami.exe created. The `> nul 2>&1` form below is what step 3 already uses.
cmd.exe /c "powershell.exe -NoProfile -Command whoami /all > nul 2>&1"
if ($LASTEXITCODE -eq 0) {
    Write-Ok 'cmd.exe -> powershell.exe -> whoami.exe'
} else {
    Write-Host "  [!]  cmd.exe returned $LASTEXITCODE - the process tree may not have been created" -ForegroundColor Yellow
}

# A base64-encoded command: legitimate in administration scripts, a classic in
# malware. Without Script Block Logging (4104) all you would see is the -enc
# blob; with it you see the decoded source.
$plain   = 'Get-Process | Select-Object -First 3'
$encoded = [Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($plain))
powershell.exe -NoProfile -EncodedCommand $encoded | Out-Null
Write-Ok "powershell.exe -EncodedCommand (decoded text was: $plain)"

# ===========================================================================
# 3 - Discovery commands  ->  T1033, T1087, T1016
# ===========================================================================
# Worth watching what happens to these: individually each one produces a generic
# process-creation event indistinguishable from a system service starting.
# Discovery is not detectable one command at a time - it is detectable as a
# sequence from the same parent inside a short window.
Write-Step '3/5  Discovery commands'

foreach ($cmd in 'whoami /priv', 'net user', 'net localgroup administrators', 'ipconfig /all', 'systeminfo') {
    cmd.exe /c "$cmd > nul 2>&1"
    Write-Ok $cmd
}

# ===========================================================================
# 4 - Simulated persistence: account, group membership, service
# ===========================================================================
Write-Step '4/5  Test account, group change and service (all removed below)'

try {
    $tempSecret = New-ThrowawaySecret
    New-LocalUser -Name $TestAccountName -Password $tempSecret -Description 'Temporary lab test account' `
        -AccountNeverExpires -ErrorAction Stop | Out-Null
    Write-Ok "account $TestAccountName created                -> 4720"

    Add-LocalGroupMember -Group 'Administrators' -Member $TestAccountName -ErrorAction Stop
    Write-Ok "$TestAccountName added to Administrators        -> 4732"

    New-Service -Name $TestServiceName -BinaryPathName 'C:\Windows\System32\cmd.exe /c exit' `
        -DisplayName 'Lab SOC test service' -StartupType Manual -ErrorAction Stop | Out-Null
    Write-Ok "service $TestServiceName created                -> 7045 (System) and 4697 (Security)"
}
finally {
    Write-Step '5/5  Cleanup'
    if (Get-Service -Name $TestServiceName -ErrorAction SilentlyContinue) {
        sc.exe delete $TestServiceName | Out-Null
        Write-Ok "service $TestServiceName removed"
    }
    if (Get-LocalUser -Name $TestAccountName -ErrorAction SilentlyContinue) {
        Remove-LocalUser -Name $TestAccountName
        Write-Ok "account $TestAccountName removed            -> 4726"
    }
}

$end = Get-Date

# ===========================================================================
# Prediction table
# ===========================================================================
Write-Host @"

==============================================================================
 TIME WINDOW
   local : $($start.ToString('HH:mm:ss'))  ->  $($end.ToString('HH:mm:ss'))   ($($start.ToString('yyyy-MM-dd')))
   UTC   : $($start.ToUniversalTime().ToString('HH:mm:ss'))Z ->  $($end.ToUniversalTime().ToString('HH:mm:ss'))Z
==============================================================================

 What was done                       Event ID    Channel
 ----------------------------------- ----------- -----------------------------
