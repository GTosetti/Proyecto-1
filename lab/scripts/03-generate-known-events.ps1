 BEFORE OPENING THE SIEM
   1. Write down which of these you think is the most serious, and why.
   2. Predict which ones will raise an alert and which will pass silently.
   3. Only then open the dashboard and compare. The prediction failures are
      the content of the writeup.

 LOCAL CHECK (layer 3 - generation, before involving the SIEM)
   Get-WinEvent -FilterHashtable @{LogName='Security'; Id=4625; StartTime=(Get-Date).AddMinutes(-30)}
   Get-WinEvent -FilterHashtable @{LogName='Security'; Id=4688; StartTime=(Get-Date).AddMinutes(-30)} |
       Select-Object -First 10 TimeCreated, @{n='Cmd';e={`$_.Properties[8].Value}}
   Get-WinEvent -LogName 'Microsoft-Windows-Sysmon/Operational' -MaxEvents 20

 FROM THE ATTACKER VM - generates what cannot be generated locally.
 Replace the placeholders; never commit real credentials.
   ping -c 4 10.10.10.20                         # ICMP
   nmap -sS -p- 10.10.10.20                      # port discovery
   for i in 1 2 3 4 5; do
       smbclient -L //10.10.10.20 -U <NONEXISTENT_USER>%<WRONG_PASSWORD>; done   # 4625 logon type 3
   xfreerdp /v:10.10.10.20 /u:<LAB_USER> /p:'<LAB_PASSWORD>' /cert:ignore        # 4624 logon type 10

 Two things measured in this lab that are worth predicting before you look:
   - The same failed password is logon type 2 from the console and logon type 3
     over SMB. Only the type field separates them.
   - With NLA enabled, a FAILED RDP login is also logon type 3, not type 10.
     Type 10 appears only once a graphical session actually establishes.
